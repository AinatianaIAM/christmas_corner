-- ============================================================
-- Christmas Corner : création des tables et contraintes
-- SGBD : PostgreSQL
-- ============================================================

DROP TABLE IF EXISTS ligne_commande CASCADE;
DROP TABLE IF EXISTS commande       CASCADE;
DROP TABLE IF EXISTS client         CASCADE;
DROP TABLE IF EXISTS produit        CASCADE;
DROP TABLE IF EXISTS categorie      CASCADE;

CREATE TABLE categorie (
    id_categorie INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom          VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE produit (
    id_produit     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom            VARCHAR(100)  NOT NULL,
    description    VARCHAR(255)  NOT NULL,
    prix           NUMERIC(10,2) NOT NULL CHECK (prix >= 0),
    quantite_stock INTEGER       NOT NULL DEFAULT 0 CHECK (quantite_stock >= 0),
    image          VARCHAR(255),
    actif          BOOLEAN       NOT NULL DEFAULT TRUE,
    id_categorie   INTEGER       NOT NULL
        REFERENCES categorie(id_categorie) ON DELETE RESTRICT
);

CREATE TABLE client (
    id_client INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom       VARCHAR(100) NOT NULL,
    telephone VARCHAR(20)  NOT NULL,
    email     VARCHAR(150) NOT NULL UNIQUE
);

CREATE TABLE commande (
    id_commande           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_client             INTEGER NOT NULL
        REFERENCES client(id_client) ON DELETE RESTRICT,
    date_commande         TIMESTAMP NOT NULL DEFAULT NOW(),
    statut_commande       VARCHAR(20) NOT NULL DEFAULT 'EN_ATTENTE'
        CHECK (statut_commande IN ('EN_ATTENTE','CONFIRMEE','TERMINEE','ANNULEE')),
    mode_reception        VARCHAR(10) NOT NULL
        CHECK (mode_reception IN ('RETRAIT','LIVRAISON')),
    adresse_livraison     VARCHAR(255),
    date_reception_prevue DATE,
    frais_livraison       NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (frais_livraison >= 0),
    statut_paiement       VARCHAR(10) NOT NULL DEFAULT 'NON_PAYE'
        CHECK (statut_paiement IN ('NON_PAYE','PAYE')),
    mode_paiement         VARCHAR(15)
        CHECK (mode_paiement IN ('ESPECES','MOBILE_MONEY')),
    date_paiement         DATE,

    -- livraison : adresse obligatoire
    CONSTRAINT ck_adresse_livraison
        CHECK (mode_reception = 'RETRAIT' OR adresse_livraison IS NOT NULL),
    -- retrait : pas de frais
    CONSTRAINT ck_frais_retrait
        CHECK (mode_reception = 'LIVRAISON' OR frais_livraison = 0),
    -- paiement cohérent
    CONSTRAINT ck_paiement
        CHECK (
            (statut_paiement = 'PAYE' AND mode_paiement IS NOT NULL AND date_paiement IS NOT NULL)
            OR
            (statut_paiement = 'NON_PAYE' AND mode_paiement IS NULL AND date_paiement IS NULL)
        ),
    -- terminée => payée
    CONSTRAINT ck_terminee_payee
        CHECK (statut_commande <> 'TERMINEE' OR statut_paiement = 'PAYE')
);

CREATE TABLE ligne_commande (
    id_commande   INTEGER NOT NULL
        REFERENCES commande(id_commande) ON DELETE CASCADE,
    id_produit    INTEGER NOT NULL
        REFERENCES produit(id_produit) ON DELETE RESTRICT,
    quantite      INTEGER NOT NULL CHECK (quantite > 0),
    prix_unitaire NUMERIC(10,2) NOT NULL CHECK (prix_unitaire >= 0),
    PRIMARY KEY (id_commande, id_produit)
);

-- ------------------------------------------------------------
-- Règle : une commande contient au moins une ligne.
-- Vérifiée en fin de transaction (contrainte différée).
-- ------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_commande_au_moins_une_ligne() RETURNS trigger AS $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM ligne_commande WHERE id_commande = NEW.id_commande) THEN
        RAISE EXCEPTION 'La commande % doit contenir au moins un produit', NEW.id_commande;
    END IF;
    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

CREATE CONSTRAINT TRIGGER trg_commande_au_moins_une_ligne
    AFTER INSERT ON commande
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW EXECUTE FUNCTION fn_commande_au_moins_une_ligne();

-- Index utiles (recherche et jointures)
CREATE INDEX idx_produit_categorie ON produit(id_categorie);
CREATE INDEX idx_commande_client   ON commande(id_client);
CREATE INDEX idx_commande_statut   ON commande(statut_commande);
